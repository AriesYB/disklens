var diskLensLanguage;

function dlText(message) {
  return diskLensLanguage === 'en' && Object.hasOwn(diskLensEnglish, message)
    ? diskLensEnglish[message]
    : message;
}

function dlNativeText(message) {
  if (diskLensLanguage !== 'en' || !message) return message;
  var translated = dlText(message);
  if (translated !== message) return translated;
  // Tauri sends diagnostic text. Keep the original details when no stable English wording is available.
  var unreadable = message.match(/^(\d+) 个子项无法读取（权限限制），迁移会在这些项上失败$/);
  if (unreadable) return unreadable[1] + ' items are unreadable. The move will fail for those items.';
  var noSpace = message.match(/^目标空间不足：需要 (.+)，目标仅剩 (.+)$/);
  if (noSpace) return 'Not enough free space. Required: ' + noSpace[1] + '. Available: ' + noSpace[2] + '.';
  var nativePrefixes = {
    '扫描完成': 'Scan complete',
    '目录刷新完成': 'Folder refresh complete',
    '无法读取源路径：': 'Could not read the source path: ',
    '目标文件夹不存在：': 'Destination folder does not exist: ',
    '目标位置已存在：': 'Destination already exists: ',
    '目标不能位于源目录内部': 'The destination cannot be inside the source folder.',
    '迁移完成': 'Move complete',
    '撤销完成': 'Undo complete',
    '复制失败：': 'Copy failed: ',
  };
  var prefix = Object.keys(nativePrefixes).find(function (key) { return message.startsWith(key); });
  return prefix ? nativePrefixes[prefix] + message.slice(prefix.length) : message;
}

(function initLanguage() {
  var key = 'disklens.locale';
  var select = document.getElementById('app-language');
  var saved;
  try { saved = localStorage.getItem(key); } catch (_) {}
  var preferred = (navigator.languages || [navigator.language]).find(function (language) {
    return /^(zh|en)(-|$)/i.test(language);
  });
  var initial = saved === 'en' || saved === 'zh-CN'
    ? saved
    : /^en\b/i.test(preferred || '') ? 'en' : 'zh-CN';

  // Capture the static labels once, before scans and dialogs create their own content.
  var labels = [];
  function addLabel(read, write, source) {
    var message = source.trim().replace(/\s+/g, ' ');
    if (!Object.hasOwn(diskLensEnglish, message)) return;
    var english = source.replace(source.trim(), diskLensEnglish[message]);
    labels.push({ read: read, write: write, chinese: source, english: english });
  }
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (var current = walker.nextNode(); current; current = walker.nextNode()) {
    if (current.parentElement.closest('script, style, #app-language option')) continue;
    (function (node) {
      addLabel(function () { return node.data; }, function (v) { node.data = v; }, node.data);
    })(current);
  }
  document.querySelectorAll('[title], [placeholder], [aria-label]').forEach(function (element) {
    ['title', 'placeholder', 'aria-label'].forEach(function (name) {
      if (!element.hasAttribute(name)) return;
      addLabel(function () { return element.getAttribute(name); }, function (v) {
        element.setAttribute(name, v);
      }, element.getAttribute(name));
    });
  });

  function apply(language) {
    diskLensLanguage = language;
    document.documentElement.lang = language;
    document.title = dlText('DiskLens 盘析 — 看清每一寸磁盘');
    select.value = language;
    labels.forEach(function (label) {
      var value = label.read();
      if (value === label.chinese || value === label.english)
        label.write(language === 'en' ? label.english : label.chinese);
    });
  }
  apply(initial);
  select.addEventListener('change', function () {
    var previous = diskLensLanguage;
    apply(select.value);
    try { localStorage.setItem(key, select.value); } catch (_) {}
    document.dispatchEvent(new CustomEvent('disklens-language-change', { detail: previous }));
  });
})();
